"""nudge 节点：一步做完却**一个改动都没产生**时，给它一次重做的机会。

要解决的缺陷
------------

`verify` 与 `review` 都只在 `dirty` 时执行。所以「这一步只读了几个文件」与
「这一步做完了」在图上**完全无法区分** —— 两者都短路通过、都直接 `advance`。

后果是实测出来的：一批长程任务里，模型把整个计划"读"了一遍就算完成，
10 次运行里 **5 次一次写都没尝试过**。计划本身是对的（"实现整单折扣"这种步骤
写得清清楚楚），缺的是**执行完那一步之后没有任何东西要求它确实做了**。

它做什么
--------

置一次标志并给一份新的工具预算，让 `act` 重来一遍；`act` 会把这件事合成进
系统提示（见 `llm/prompts.py::compose_system_prompt`），明确告诉模型：
这一步还没有产生任何改动；**如果它本来就需要改动，现在做**；如果这一步本就
只需只读（例如"先探索项目结构"），说明理由后停下即可。

为什么是"一次"而不是"循环到有改动为止"
--------------------------------------

只读步骤是**合法**的（计划的第一步常常就是探索）。无限要求"必须有改动"会逼出
无意义的改动。所以这里只给一次机会，并由模型自己判断要不要用它 ——
nudge 的措辞里明确给了"这一步本就是只读"这条退路。

与 `repair` 的分工：`repair` 处理的是"做了但不合格"（验证失败 / 审查阻断），
本节点处理的是"压根没做"。两者都在 `advance` 之前，但互斥：没改动就不可能
触发 verify/review，也就不会进 repair。
"""

from __future__ import annotations

from typing import Any

from coding_agent.graph.state import AgentState


def nudge(state: AgentState) -> dict[str, Any]:
    return {
        "empty_step_nudged": True,
        # 上一步的轮次可能已经用光 —— 不给新预算的话 act 会立刻以"预算耗尽"收尾，
        # 这次机会等于没给。
        "tool_rounds": 0,
        "budget_exhausted": False,
    }
